async def build_pdf():
    html_file = os.path.abspath("ninja_master_atlas.html")
    pdf_file = os.path.abspath("Ninja_Smart_Factory_Master_Operational_Atlas.pdf")
    
    print(f"Writing master HTML to {html_file}...")
    with open(html_file, "w", encoding="utf-8") as f:
        f.write(master_html)
    
    print("Launching Playwright to render Master PDF (A4 Landscape)...")
    async with async_playwright() as p:
        browser = await p.chromium.launch()
        page = await browser.new_page()
        # Navigate with networkidle
        await page.goto(f"file:///{html_file.replace(os.sep, '/')}", wait_until="networkidle")
        await page.wait_for_timeout(1000)
        
        await page.pdf(
            path=pdf_file,
            format="A4",
            landscape=True,
            print_background=True,
            margin={"top": "0mm", "bottom": "0mm", "left": "0mm", "right": "0mm"}
        )
        await browser.close()
    
    file_size_mb = os.path.getsize(pdf_file) / (1024 * 1024)
    print(f"Master PDF generated successfully! Path: {pdf_file} (Size: {file_size_mb:.2f} MB)")

if __name__ == "__main__":
    asyncio.run(build_pdf())
